import { createRequire } from "node:module";
import { readFileSync, readdirSync, statSync } from "node:fs";
import { dirname, join } from "node:path";
import { describe, expect, it } from "vitest";
import { mapElectronUpdaterError } from "./electronUpdaterErrorMap.js";

const require_ = createRequire(import.meta.url);

// Every `.js` file's text under `dir`, recursing except `skipDirs`/`skipFiles`.
function readSourceFiles(
  dir: string,
  skipDirs: readonly string[],
  skipFiles: readonly string[],
): string[] {
  const texts: string[] = [];
  for (const entry of readdirSync(dir)) {
    if (skipDirs.includes(entry)) continue;
    const full = join(dir, entry);
    if (statSync(full).isDirectory()) {
      texts.push(...readSourceFiles(full, skipDirs, skipFiles));
    } else if (entry.endsWith(".js") && !skipFiles.includes(entry)) {
      texts.push(readFileSync(full, "utf8"));
    }
  }
  return texts;
}

// Every literal `ERR_*` code passed as `newError(message, code)`'s final
// argument -- matched by that shape (code immediately before the closing
// `)`) since the free-form message argument may itself contain commas.
function extractErrCodes(sources: readonly string[]): Set<string> {
  const codes = new Set<string>();
  const pattern = /,\s*["'](ERR_[A-Z0-9_]+)["']\s*\)/g;
  for (const source of sources) {
    for (const match of source.matchAll(pattern)) {
      const code = match[1];
      if (code !== undefined) codes.add(code);
    }
  }
  return codes;
}

describe("electron-updater / builder-util-runtime exhaustiveness", () => {
  it("accounts for every real ERR_* code the installed libraries can throw on a reachable path", () => {
    const electronUpdaterOut = dirname(require_.resolve("electron-updater"));
    const builderUtilRuntimePkg = require_.resolve("builder-util-runtime/package.json", {
      paths: [electronUpdaterOut],
    });
    const builderUtilRuntimeOut = join(dirname(builderUtilRuntimePkg), "out");

    const realCodes = extractErrCodes([
      // `differentialDownloader/*` errors are caught by
      // `AppUpdater.differentialDownloadInstaller` and converted into a
      // silent fallback to a full download, so none reach the public `error` event.
      ...readSourceFiles(electronUpdaterOut, ["differentialDownloader"], []),
      // `uuid.js`: electron-updater only calls `UUID.v5` with its own fixed
      // namespace and library-generated bytes, so `ERR_INVALID_UUID_NAME`/
      // `ERR_UNKNOWN_UUID_TYPE` guard an invariant no input can violate.
      ...readSourceFiles(builderUtilRuntimeOut, [], ["uuid.js"]),
    ]);

    // Sanity check on the scrape itself: if this ever comes back empty, the
    // regex or the resolved paths broke, not the dependency's error surface.
    expect(realCodes.size).toBeGreaterThan(0);

    const unaccountedFor = [...realCodes].filter((code) => {
      const result = mapElectronUpdaterError(Object.assign(new Error("x"), { code }), "idle");
      return result.failureMode === "unknown";
    });

    expect(unaccountedFor).toEqual([]);
  });
});

describe("Electron builtin autoUpdater (Squirrel.Mac) exhaustiveness", () => {
  it("pins the exact installed `electron` version this SDK's Squirrel.Mac domain/code audit covers", () => {
    // Squirrel.Mac is vendored into Electron's native binary, not an
    // inspectable npm dependency, so there's no source to scrape the way
    // the electron-updater test above does.
    //
    // This pins the exact version the domain/code tables in
    // `builtinUpdaterErrorMap.ts` were last audited against; any version
    // bump fails this test, forcing a manual re-check before updating the pin.
    const AUDITED_ELECTRON_VERSION = "42.11.16";

    const installedVersion = (require_("electron/package.json") as { version: string }).version;

    expect(installedVersion).toBe(AUDITED_ELECTRON_VERSION);
  });
});
